import assert from 'node:assert/strict';
import {hatchKind,hatchId,hatchSVGDefs,openingPlanGeometry,openingSVG} from '../src/detail-graphics.mjs';
import {buildPlotSVG} from '../src/plot.mjs';
assert.equal(hatchKind('Cast in situ Concrete'),'concrete');
assert.equal(hatchKind('CMU masonry'),'masonry');
assert.equal(hatchKind('Structural steel'),'metal');
assert.equal(hatchKind('Timber'),'timber');
assert.equal(hatchId('Insulation'),'h-insulation');
assert.match(hatchSVGDefs,/h-glass/);
const w={id:'W1',type:'wall',x1:0,y1:0,x2:4000,y2:0,z:0,thickness:200,height:3000,material:'Concrete'};
const d={id:'D1',hostId:'W1',type:'door',u:.5,width:900,height:2100,z:0};
const n={id:'N1',hostId:'W1',type:'window',u:.75,width:900,height:1200,z:900};
const map=(x,y)=>[x/50,y/50];
assert.equal(openingPlanGeometry(w,d).width,900);
assert.match(openingSVG(w,d,map,50),/data-bim-symbol="door"/);
assert.match(openingSVG(w,d,map,50),/ A18 18 /);
assert.match(openingSVG(w,n,map,50),/data-bim-symbol="window"/);
const doc={title:'test',elements:[w,d,n]};
const svg=buildPlotSVG(doc,{views:'single',mainView:'plan',scale:50});
assert.match(svg,/data-bim-symbol="door"/);
assert.match(svg,/data-bim-symbol="window"/);
assert.match(svg,/h-concrete/);
assert.match(svg,/url\(#h-concrete\)/);
console.log('2D detail graphic assertions passed');
